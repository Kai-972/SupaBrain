// zod schemas for config/*.json. Browser-safe (no node imports); the loader is in ./config.ts.
import { z } from "zod";

export const HexAddress = z
  .string()
  .regex(/^0x[0-9a-fA-F]{40}$/, "expected a 0x-prefixed 20-byte address")
  .transform((v) => v as `0x${string}`);
const Usdc = z.string().regex(/^\d+(\.\d{1,6})?$/, "expected a decimal USDC amount (max 6 decimals)");
const Label = z.string().regex(/^[a-z0-9-]+$/, "expected a lowercase ENS label");
const VerifiedAt = z.string().regex(/^\d{4}-\d{2}-\d{2}/, "expected an ISO date");
const Sourced = { source: z.url(), verifiedAt: VerifiedAt };
const Explorer = z.object({ base: z.url(), tx: z.string().includes("{hash}"), address: z.string().includes("{address}") });

// Arkiv max entity lifetime is ~182 d; revocations ("max") must outlive any kept memory.
const ARKIV_MAX_LIFETIME_DAYS = 182;

export const AppFileSchema = z
  .object({
    appNamespace: z.string().min(1),
    team: z.object({ id: z.string().min(1), displayName: z.string().min(1) }),
    server: z.object({ port: z.number().int().positive() }),
    ens: z.object({
      teamLabel: Label.nullable(), // ASK in S1
      leaseDays: z.number().int().positive(),
      teamNameDurationDays: z.number().int().positive(),
      textKeys: z.object({
        role: z.string(), scope: z.string(), payCap: z.string(), payDaily: z.string(), status: z.string(),
        memoryHead: z.string(), vendor: z.string(), agentContext: z.string(), agentEndpointMcp: z.string(),
      }),
    }),
    agents: z
      .array(
        z.object({
          label: Label,
          vendor: z.enum(["claude", "gemini", "openai"]),
          role: z.enum(["lead", "worker", "observer"]),
          scope: z.string().min(1),
          payCapUsdc: Usdc,
          payDailyUsdc: Usdc,
          vaultDailyCeilingUsdc: Usdc,
        }),
      )
      .min(1),
    vendors: z.array(z.object({ label: Label, displayName: z.string().min(1) })),
    trust: z.object({ human: z.literal(3), agent: z.literal(2), evidence: z.literal(1) }),
    readSet: z.object({ ttlSec: z.number().int().positive() }),
    keep: z.object({ defaultDays: z.number().int().positive(), maxDays: z.number().int().positive() }),
    payments: z.object({
      intentTtlSec: z.number().int().positive(),
      attestationTtlSec: z.number().int().positive(),
      maxRootsPerAttestation: z.number().int().positive(),
      eip712: z.object({ name: z.string().min(1), version: z.string().min(1) }), // BrainVault EIP-712 domain (constructor args)
    }),
    arkivExpirySec: z.object({
      memory: z.number().int().positive(),
      evidence: z.number().int().positive(),
      edge: z.literal("follow-child"),
      taint: z.literal("follow-memory"),
      notice: z.number().int().positive(),
      paymentIntent: z.number().int().positive(),
      paymentDecision: z.number().int().positive(),
      revocation: z.literal("max"),
    }),
    refs: z.object({ allowedKinds: z.array(z.enum(["github", "notion", "url"])).min(1) }),
  })
  .refine((c) => c.keep.defaultDays <= c.keep.maxDays, { message: "keep.defaultDays must be <= keep.maxDays", path: ["keep"] })
  .refine((c) => c.keep.maxDays < ARKIV_MAX_LIFETIME_DAYS, { message: "keep.maxDays must be below the Arkiv max lifetime so revocations outlive kept memories", path: ["keep", "maxDays"] })
  .refine((c) => new Set(c.agents.map((a) => a.label)).size === c.agents.length, { message: "agent labels must be unique", path: ["agents"] });

export const NetworksFileSchema = z.object({
  sepolia: z.object({ chainId: z.number().int(), name: z.string(), rpcEnv: z.string(), explorer: Explorer, ...Sourced }),
  rabdi: z.object({
    chainId: z.number().int(), name: z.string(), rpc: z.url(), explorer: Explorer,
    ws: z.string().startsWith("wss://"), // hardcode-ok: protocol prefix check, not an endpoint
    faucet: z.url(), accessKeys: z.url(), nativeSymbol: z.string(), ...Sourced,
  }),
});

export const TokensFileSchema = z.object({
  usdc: z.object({ symbol: z.string(), address: HexAddress, decimals: z.literal(6), faucet: z.url(), ...Sourced }),
});

// config/ens.sepolia.json: hand-copied ENSv2 deployment addresses (filled in S1).
export const EnsFileSchema = z.object({
  note: z.string().optional(),
  source: z.url(),
  verifiedAt: VerifiedAt.nullable(),
  redeployedAt: z.string().nullable(),
  commit: z.string().regex(/^[0-9a-f]{40}$/).optional(),
  abiSource: z.url().optional(),
  contracts: z.record(z.string(), HexAddress),
});

// config/world.json is Lane B's; kept loose here so B can tighten it.
export const WorldFileSchema = z.looseObject({
  issuer: z.url().nullable().optional(),
  scope: z.string().optional(),
  requireEnrolledSub: z.boolean().optional(),
  approvalTtlSec: z.number().int().positive().optional(),
});

export const DemoScenarioFileSchema = z.looseObject({ vendor: Label });

// config/deployments/*.json are generated by scripts and committed (they are proof). Vault deployments are Lane B's.
export const DeploymentFileSchema = z.looseObject({});

const Hex32 = z.string().regex(/^0x[0-9a-fA-F]{64}$/);
const Tx = z.object({ hash: Hex32, url: z.url(), at: z.string().optional() });
const EnsAgentDeployment = z.object({
  label: Label,
  ens: z.string(),
  labelhash: Hex32, // 0x-prefixed bytes32; the vault takes BigInt(labelhash) as the uint256 id
  wallet: HexAddress,
  resolver: HexAddress,
  resolverSalt: z.string(), // decimal uint256
  expiry: z.number().int(), // unix seconds
  txs: z.record(z.string(), Tx),
  records: z.record(z.string(), z.string()), // text records written at initialisation
  throwaway: z.boolean().optional(),
  unregisteredAt: z.string().optional(), // set by scripts/ens/unregister.ts (the kill switch)
});
/** config/deployments/ens.sepolia.json: written step by step by scripts/ens/*, read by packages/ens and Lane B. */
export const EnsDeploymentSchema = z.object({
  network: z.string(),
  chainId: z.number().int(),
  team: z
    .object({
      label: Label, name: z.string(), labelhash: Hex32, owner: HexAddress,
      expiry: z.number().int(), txs: z.record(z.string(), Tx),
    })
    .optional(),
  teamRegistry: z
    .object({
      address: HexAddress, implementation: HexAddress, factory: HexAddress, salt: z.string(), owner: HexAddress,
      txs: z.record(z.string(), Tx),
    })
    .optional(),
  agents: z.record(z.string(), EnsAgentDeployment),
  vendors: z.record(z.string(), z.looseObject({})),
});
export type EnsDeployment = z.infer<typeof EnsDeploymentSchema>;
export type EnsAgentDeployment = z.infer<typeof EnsAgentDeployment>;

export type AppFile = z.infer<typeof AppFileSchema>;
export type NetworksFile = z.infer<typeof NetworksFileSchema>;
export type TokensFile = z.infer<typeof TokensFileSchema>;
export type EnsFile = z.infer<typeof EnsFileSchema>;
export type WorldFile = z.infer<typeof WorldFileSchema>;

// Everything non-secret. Secrets are read separately with requireEnv() so they never ride inside config objects.
export interface AppConfig {
  app: AppFile;
  networks: NetworksFile;
  tokens: TokensFile;
  ens: EnsFile;
  world: WorldFile | null;
  demo: z.infer<typeof DemoScenarioFileSchema>;
  deployments: { ens: EnsDeployment | null; vault: Record<string, unknown> | null };
}

const opt = <T extends z.ZodType>(s: T) => z.preprocess((v) => (v === "" ? undefined : v), s.optional());
const PrivateKey = opt(z.string().regex(/^0x[0-9a-fA-F]{64}$/, "expected a 0x-prefixed 32-byte hex private key"));

export const EnvSchema = z.looseObject({
  SEPOLIA_RPC_URL: opt(z.url()),
  ARKIV_ACCESS_KEY: opt(z.string().min(1)),
  OWNER_PRIVATE_KEY: PrivateKey,
  TEAM_PRIVATE_KEY: PrivateKey,
  VENDOR_ACME_PRIVATE_KEY: PrivateKey,
  POLICY_SIGNER_PRIVATE_KEY: PrivateKey,
  GUARDIAN_PRIVATE_KEY: PrivateKey,
  WORLD_APP_ID: opt(z.string()),
  WORLD_RP_ID: opt(z.string()),
  WORLD_SIGNING_KEY: opt(z.string().min(8)),
  WORLD_CLIENT_ID: opt(z.string()),
  WORLD_CLIENT_SECRET: opt(z.string()),
  WORLD_APPROVER_SUB_HASH: opt(z.string()),
  NOTION_TOKEN: opt(z.string()),
  PUBLIC_BASE_URL: opt(z.url()),
  TOKEN_SIGNING_SECRET: opt(z.string().min(32, "TOKEN_SIGNING_SECRET must be at least 32 chars")),
  DASHBOARD_ADMIN_PASSPHRASE: opt(z.string().min(8)),
  NEXT_PUBLIC_SERVER_URL: opt(z.url()),
  PORT: opt(z.coerce.number().int().positive()),
});
export type Env = z.infer<typeof EnvSchema>;
