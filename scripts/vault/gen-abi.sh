#!/usr/bin/env bash
# Regenerates packages/payments/src/vault/abi.ts from the compiled BrainVault (run after any contract change).
set -euo pipefail
cd "$(dirname "$0")/../../contracts"
forge build --silent
out=../packages/payments/src/vault/abi.ts
{
  echo "// GENERATED by scripts/vault/gen-abi.sh from contracts/src/BrainVault.sol. Do not edit by hand."
  printf "export const brainVaultAbi = %s as const;\n" "$(forge inspect BrainVault abi --json)"
} > "$out"
echo "wrote $out"
